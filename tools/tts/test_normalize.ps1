# ko_normalize.ps1 시험 — 지시서 §3 의 예를 전부 넣었다(pytest 대신. 이 PC 에 Python 없음).
# 쓰는 법: powershell -NoProfile -File test_normalize.ps1   → 끝에 「통과 N / N」, 하나라도 틀리면 종료 코드 1
[Console]::OutputEncoding = [Text.Encoding]::UTF8
. "$PSScriptRoot\ko_normalize.ps1"
$cases = @(
  @('30km/h', '시속 삼십 킬로미터'),
  @('112', '일일이'), @('119', '일일구'), @('182', '일팔이'),
  @('010-1234-5678', '공일공, 일이삼사, 오육칠팔'),
  @('12가3456', '일이 가 삼사오육'), @('123가4567', '일이삼 가 사오육칠'),
  @('서초대로77길', '서초대로 칠십칠 길'), @('219', '이백십구'),
  @('3번 출구', '삼 번 출구'), @('1차로', '일 차로'), @('2호선', '이 호선'),
  @('3명', '세 명'), @('2대', '두 대'), @('20명', '스무 명'), @('21명', '스물한 명'), @('3시', '세 시'), @('100명', '백 명'),
  @('3번 위반', '세 번 위반'),
  @('14:30', '오후 두 시 삼십 분'), @('09:05', '오전 아홉 시 오 분'),
  @('6월', '유월'), @('10월', '시월'), @('3월 5일', '삼월 오 일'),
  @('0.03%', '영 점 영삼 퍼센트'), @('0.08%', '영 점 영팔 퍼센트'),
  @('제44조제1항', '제사십사조 제일항'), @('§68③5', '제육십팔조 제삼항 제오호'), @('§148의2', '제백사십팔조의이'),
  @('50,000원', '오만 원'), @('5만원', '오만 원'), @('벌점 10점', '벌점 십 점'),
  @('IC', '아이씨'), @('CCTV', '씨씨티비'), @('BRT', '비알티'),
  @('서울(으)로', '서울로'), @('서초(으)로', '서초로'), @('반포동(으)로', '반포동으로'), @('경찰관(이)가', '경찰관이'), @('차(이)가', '차가'),
  @('음주측정은 호흡측정이 원칙입니다.', '음주측정은 호흡측정이 원칙입니다.')
)
$ok = 0; $bad = 0
foreach ($c in $cases) {
  $w = $null; $got = Convert-KoSpoken $c[0] ([ref]$w)
  if ($got -ceq $c[1]) { $ok++ } else { $bad++; "  틀림  {0}  →  「{1}」 (기대 「{2}」)" -f $c[0], $got, $c[1] }
}
# 모르는 약어 경고
$w = $null; [void](Convert-KoSpoken 'XYZ 단속' ([ref]$w)); if (@($w) -contains 'XYZ') { $ok++ } else { $bad++; '  틀림  모르는 약어 경고 없음' }
# 조사 고르기
if ((Select-KoJosa '길' '(으)로') -eq '로' -and (Select-KoJosa '집' '(으)로') -eq '으로') { $ok++ } else { $bad++; '  틀림  ㄹ 받침 (으)로' }
"NORMALIZER_VERSION {0} · 통과 {1} / {2}" -f $NORMALIZER_VERSION, $ok, ($ok + $bad)
if ($bad) { exit 1 }
